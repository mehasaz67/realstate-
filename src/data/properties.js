export const featuredProperties = properties.filter((property) => property.featured)

export const locations = [...new Set(properties.map((property) => property.location))].sort()

export const propertyTypes = [...new Set(properties.map((property) => property.type))].sort()

export const getProperty = (id) => properties.find((property) => property.id === id)

export const similarProperties = (property, limit = 3) =>
  properties
    .filter((candidate) => candidate.id !== property.id)
    .sort((a, b) => {
      const score = (item) =>
        (item.city === property.city ? 2 : 0) + (item.type === property.type ? 1 : 0)
      return score(b) - score(a)
    })
    .slice(0, limit)
